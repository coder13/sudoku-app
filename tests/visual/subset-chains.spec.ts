import { expect, test, type Page } from '@playwright/test'

const workbench = (story = 'subset-workbench') => `/iframe.html?id=large-play-worktable--${story}&viewMode=story`
const cell = (page: Page, index: number) => page.locator(`[role="gridcell"][data-cell="${index}"]`)
const panel = (page: Page) => page.getByRole('region', { name: 'Subsets', exact: true })
const boardMenu = (page: Page) => page.getByRole('menu', { name: 'Puzzle board actions' })
const subset = (page: Page, number: number) => panel(page).getByRole('button', { name: `Set ${number}`, exact: true })
const chains = (page: Page) => page.getByRole('region', { name: 'Chains', exact: true })

async function chooseChainAction(page: Page, name: string) {
  await chains(page).getByRole('button', { name: 'Chain actions', exact: true }).click()
  await page.getByRole('menu', { name: 'Chain actions', exact: true }).getByRole('menuitem', { name, exact: true }).click()
}

async function showEliminations(page: Page, tool: 'Chain' | 'Subset') {
  await page.getByRole('button', { name: `${tool} display options` }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Show eliminations' }).click()
  await page.keyboard.press('Escape')
}

test('right-click saves the selected cells and the subset uses the chain card pattern', async ({ page }) => {
  await page.goto(workbench())
  const subsets = panel(page)
  await expect(subsets.getByRole('button', { name: 'New subset' })).toBeVisible({ timeout: 20000 })
  await expect(subsets.getByRole('button', { name: 'Make subset' })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Chains', exact: true }).click()
  await cell(page, 24).click()
  await cell(page, 25).click({ modifiers: ['Shift'] })
  await cell(page, 24).click({ button: 'right' })
  const make = boardMenu(page).getByRole('menuitem', { name: 'Make subset' })
  await expect(make).toBeFocused()
  await make.click()
  await expect(boardMenu(page)).toBeHidden()
  const card = subsets.getByRole('button', { name: 'Set 1', exact: true })
  await expect(card).toHaveAttribute('aria-pressed', 'true')
  await expect(card).toHaveAccessibleDescription('ALS Candidates 2, 4, 7')
  await expect(cell(page, 24)).toHaveAttribute('aria-label', /Set 1/)
  await expect(cell(page, 24).locator('.cell-set-tint')).toHaveCount(1)
  await expect(cell(page, 25)).toHaveAttribute('aria-label', /Set 1/)
  await subsets.getByRole('button', { name: 'Hide Set 1' }).click()
  await expect(cell(page, 24)).not.toHaveAttribute('aria-label', /Set 1/)
  await expect(cell(page, 24).locator('.cell-set-tint')).toHaveCount(0)
  await expect(card).toHaveAttribute('aria-pressed', 'true')
  await subsets.getByRole('button', { name: 'Show Set 1' }).click()
  await expect(cell(page, 24)).toHaveAttribute('aria-label', /Set 1/)

  const edit = subsets.getByRole('button', { name: 'Edit Set 1' })
  expect((await edit.boundingBox())!.x).toBeLessThan((await subsets.getByRole('button', { name: 'Hide Set 1' }).boundingBox())!.x)
  await edit.click()
  await cell(page, 22).click()
  await expect(card.getByText('2479', { exact: true })).toBeVisible()
  await cell(page, 22).press('Escape')
  await expect(subsets.getByRole('button', { name: 'Done editing subsets' })).toHaveCount(0)
  await expect(card.getByText('2479', { exact: true })).toBeVisible()
  await expect(subsets).not.toContainText(/Shared houses|Extra candidates/)
  await expect(subsets.getByText('Cells', { exact: true })).toHaveCount(0)
  await expect(cell(page, 22)).toHaveAttribute('aria-label', /Set 1/)
  await subsets.getByRole('button', { name: 'Delete Set 1' }).click()
  await expect(card).toHaveCount(0)
  await expect(cell(page, 22)).not.toHaveAttribute('aria-label', /Set 1/)

  await page.getByRole('tab', { name: 'Chains', exact: true }).click()
  const chains = page.getByRole('region', { name: 'Chains', exact: true })
  await expect(chains.getByRole('button', { name: 'Chain 1', exact: true })).toBeVisible()
  await expect(chains.getByRole('group', { name: 'Edit chain 1' })).toBeVisible()
  await expect(chains.getByText('Chains with subsets')).toHaveCount(0)
  await expect(chains.getByRole('button', { name: 'Apply subset deduction' })).toHaveCount(0)
})

test('board context menu supports keyboard control and rejects incompatible cells', async ({ page }) => {
  await page.goto(workbench())
  await cell(page, 22).click()
  await cell(page, 36).click({ modifiers: ['ControlOrMeta'] })
  await cell(page, 36).press('Shift+F10')
  const menu = boardMenu(page)
  const make = menu.getByRole('menuitem', { name: 'Make subset' })
  await expect(make).toBeDisabled()
  await menu.press('Escape')
  await expect(menu).toBeHidden()
  await expect(cell(page, 36)).toBeFocused()

  // A cell outside the selection becomes the sole target of the action.
  await cell(page, 3).press('Shift+F10')
  await expect(make).toBeFocused()
  await page.keyboard.press('Space')
  await expect(menu).toBeHidden()
  await expect(cell(page, 3)).toHaveAttribute('aria-label', /Set 1/)
  await expect(cell(page, 22)).not.toHaveAttribute('aria-label', /Set 1/)
  await expect(cell(page, 36)).not.toHaveAttribute('aria-label', /Set 1/)
})

