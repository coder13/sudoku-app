test.describe('touch subset mode', () => {
  test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })

  test('hint sets tint and border overlapping memberships while manual color stays a fill', async ({ page }) => {
    await page.goto('/iframe.html?id=medium-grid-sudoku-grid--overlapping-almost-locked-sets&viewMode=story')
    const painted = page.getByRole('gridcell', { name: /Cell colors blue.*Set 1, Set 2/ })
    await expect(painted).toBeVisible({ timeout: 20000 })
    await expect(painted).toHaveCSS('background-color', 'rgb(204, 225, 252)')
    const tint = painted.locator('.cell-set-tint')
    await expect(tint).toHaveCSS('background-image', /^conic-gradient/)
    await expect(tint).toHaveCSS('border-image-source', /^conic-gradient/)
    await expect(tint).toHaveCSS('pointer-events', 'none')
    const tintWidth = await tint.evaluate(node => parseFloat(getComputedStyle(node).borderTopWidth))
    expect(tintWidth).toBeGreaterThanOrEqual(2)
    const manualColor = page.getByRole('gridcell', { name: /Cell colors blue(?!.*Set [12])/ })
    await expect(manualColor).toHaveCSS('background-color', 'rgb(204, 225, 252)')
    await expect(manualColor.locator('.cell-set-tint')).toHaveCount(0)
  })

  test('tapping eligible cells saves a subset without editing the puzzle', async ({ page }) => {
    await page.goto(workbench())
    const subsets = panel(page)
    const done = subsets.getByRole('button', { name: 'Done editing subsets' })
    await subsets.getByRole('button', { name: 'New subset' }).tap()
    await cell(page, 22).tap()
    await expect(subset(page, 1)).toBeVisible()
    await expect(cell(page, 24)).toHaveAttribute('aria-label', /Can join subset/)
    await expect(cell(page, 36)).not.toHaveAttribute('aria-label', /Can join subset/)
    await cell(page, 36).tap()
    await cell(page, 24).tap()
    await cell(page, 25).tap()
    await expect(subset(page, 1)).toHaveAccessibleDescription('ALS Candidates 2, 4, 7, 9')
    await done.tap()
    await expect(done).toHaveCount(0)
    await expect(subset(page, 1)).toHaveAccessibleDescription('ALS Candidates 2, 4, 7, 9')
    await expect(cell(page, 22)).toHaveAttribute('aria-label', /Set 1/)
    await expect(cell(page, 36)).not.toHaveAttribute('aria-label', /Set 1/)
    await page.getByRole('tab', { name: 'Digits', exact: true }).tap()
    await expect(subsets).toBeHidden()
    await expect(cell(page, 22)).toHaveAttribute('aria-label', /Set 1/)
    await page.getByRole('tab', { name: 'Subsets', exact: true }).tap()
    await page.getByRole('button', { name: 'Close subsets panel' }).tap()
    await expect(cell(page, 22)).not.toHaveAttribute('aria-label', /Set 1/)
  })
})
