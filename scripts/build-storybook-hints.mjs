import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { DIFFICULTY_LABELS } from '../src/sudoku/difficulty.ts'
import { techniqueLabel } from '../src/sudoku/hints.ts'

const engine = new URL('../src/sudoku/generated/', import.meta.url)
const output = new URL('../stories/generated/', import.meta.url)
const readJson = async (name) => JSON.parse(await readFile(new URL(name, engine), 'utf8'))
const [techniques, examples] = await Promise.all([
  readJson('lesson-difficulties.json'),
  readJson('lesson-examples.json'),
])

for (const [id, difficulty] of Object.entries(techniques)) {
  if (!Object.hasOwn(DIFFICULTY_LABELS, difficulty) ||
    examples[id]?.deduction.technique !== id || !examples[id].deduction.actions.length) {
    throw new Error(`The Storybook hint for "${id}" needs a verified engine deduction and difficulty.`)
  }
}

await mkdir(output, { recursive: true })
for (const [difficulty, label] of Object.entries(DIFFICULTY_LABELS)) {
  const variants = Object.entries(techniques)
    .filter(([, level]) => level === difficulty)
    .map(([id]) => `export const ${storyExport(id)} = { ...techniqueStory(${JSON.stringify(id)}), name: ${JSON.stringify(techniqueLabel(id))} }`)
  const source = `// Generated by scripts/build-storybook-hints.mjs.
import { hintMeta, techniqueStory } from '../support/hint-stories'

export default { ...hintMeta, title: 'Small/Hints/${label}', tags: ['!autodocs'] }

${variants.join('\n')}
`
  await writeFile(new URL(`${difficulty}.stories.tsx`, output), source)
}

function storyExport(id) {
  return 'Hint' + id.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('')
}
